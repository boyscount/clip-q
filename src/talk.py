def get(talk_id: str | None):
    """สไตล์ที่ขอ — None หรือ 'auto' แปลว่าให้ใช้ของแนวคลิปแทน"""
    return TALKS.get((talk_id or "").strip())


def pick(talk_id: str | None, seed: int | None = None):
    """เลือกสไตล์ 'random' สุ่มหนึ่งอัน เพื่อให้คลิปชุดเดียวกันไม่พูดเหมือนกันหมด"""
    wanted = (talk_id or "").strip()
    if wanted == "random":
        return random.Random(seed).choice(sorted(TALKS.values(), key=lambda t: t.id))
    return get(wanted)


